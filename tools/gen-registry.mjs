#!/usr/bin/env node
// Regenerate Sources/CLibretro/include/cores_list.h from tools/cores.json.
//
// The header is COMMITTED (so the C registry is reviewable and `swift build` works
// without running this first); CI asserts it matches cores.json, same as testrom.nes
// is asserted against its generator. Run this after editing cores.json.
//
// Core `name` doubles as (a) the registry lookup key — it is the EmulatorJS core alias
// the classicgame frontend sends over the wire (segaMD, pce, ...), NOT the libretro
// repo name — and (b) the C symbol prefix (segaMD_retro_run), so it must be a valid
// C identifier.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const cores = JSON.parse(readFileSync(join(root, 'tools/cores.json'), 'utf8'));

for (const c of cores) {
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(c.name)) {
    throw new Error(`core name "${c.name}" is not a valid C identifier`);
  }
}

const header = `/* GENERATED by tools/gen-registry.mjs from tools/cores.json — do not edit.
 * One CORE(name) per statically linked core; cores.c defines CORE twice (extern
 * prototypes, then vtable entries) and includes this file each time (X-macro). */
${cores.map((c) => `CORE(${c.name})`).join('\n')}
`;

const out = join(root, 'Sources/CLibretro/include/cores_list.h');
writeFileSync(out, header);
console.log(`wrote ${out} (${cores.length} cores: ${cores.map((c) => c.name).join(', ')})`);
